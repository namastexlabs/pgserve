/**
 * pg_hba.conf B1-fixed template (Group 2, autopg-distribution-cutover wish).
 *
 * Sentinel B1 acceptance: "zero `trust` predicates for any user". The
 * default initdb output ships `local all all trust` and
 * `local replication all trust`, both of which are superuser-as-a-service
 * via pg_hba first-match. This module overwrites those with a layout that
 * has zero `trust` lines:
 *
 *   - admin local socket via peer + pg_ident map (kernel-enforced UID match)
 *   - everything else via scram-sha-256
 *
 * Wired into `src/postgres.js` `start()` after `_bootstrapAdmin()` so the
 * `autopg_admin` role + on-disk SCRAM secret already exist when we flip
 * the auth method. Postmaster reload (SIGHUP) picks up the new config
 * without dropping in-flight connections.
 *
 * pg_ident.conf is co-managed: the autopg map binds the host OS user
 * to `autopg_admin`, so peer auth resolves to the admin role even when
 * the OS user has a different name.
 */

import fs from 'fs';
import os from 'os';
import path from 'path';
import { ADMIN_ROLE } from './admin-bootstrap.js';
import { audit, AUDIT_EVENTS } from '../audit.js';

const HBA_FILENAME = 'pg_hba.conf';
const IDENT_FILENAME = 'pg_ident.conf';
export const IDENT_MAP_NAME = 'autopg';

/**
 * Render the B1-fixed pg_hba.conf body as a string.
 *
 * Layout (post-rewrite):
 *   1. Replication: scram on socket + loopback (defends against operator
 *      footguns even though autopg currently does not run replicas).
 *   2. Admin: local socket → autopg_admin via peer (mapped through
 *      pg_ident.conf to the host OS user).
 *   3. Loopback TCP: scram-sha-256.
 *   4. Catch-all local socket for non-admin roles: scram-sha-256.
 *
 * @param {object} [opts]
 * @param {string} [opts.adminRole] - admin role name (default: autopg_admin)
 * @param {string} [opts.identMapName] - pg_ident map name (default: autopg)
 * @returns {string}
 */
export function renderPgHba({ adminRole = ADMIN_ROLE, identMapName = IDENT_MAP_NAME } = {}) {
  const lines = [
    '# autopg pg_hba.conf — Sentinel B1 layout',
    '# Generated by autopg; manual edits are overwritten on upgrade.',
    '#',
    '# Zero `trust` predicates anywhere. Local admin is gated by peer auth',
    '# (kernel-enforced UID match via pg_ident.conf); everything else is',
    '# scram-sha-256.',
    '',
    '# TYPE  DATABASE        USER            ADDRESS                 METHOD',
    '',
    '# Replication: SCRAM-only on socket + loopback (no `trust`).',
    'local   replication     all                                     scram-sha-256',
    'host    replication     all             127.0.0.1/32            scram-sha-256',
    'host    replication     all             ::1/128                 scram-sha-256',
    '',
    '# Admin local socket: OS user mapped to autopg_admin via pg_ident.',
    `local   all             ${adminRole}                            peer            map=${identMapName}`,
    '',
    '# Loopback TCP: SCRAM only (daemon binds localhost).',
    'host    all             all             127.0.0.1/32            scram-sha-256',
    'host    all             all             ::1/128                 scram-sha-256',
    '',
    '# Catch-all local socket for non-admin roles: SCRAM.',
    'local   all             all                                     scram-sha-256',
    '',
  ];
  return lines.join('\n');
}

/**
 * Render the pg_ident.conf body that maps the host OS user to the admin
 * PG role. Without this, `peer map=autopg` rejects connections because no
 * OS-user → PG-user mapping exists for the autopg map.
 *
 * @param {object} opts
 * @param {string} opts.osUser - host OS user (typically `os.userInfo().username`)
 * @param {string} [opts.adminRole]
 * @param {string} [opts.identMapName]
 * @returns {string}
 */
export function renderPgIdent({ osUser, adminRole = ADMIN_ROLE, identMapName = IDENT_MAP_NAME }) {
  if (!osUser || typeof osUser !== 'string') {
    throw new Error('renderPgIdent: osUser is required');
  }
  // pg_ident regex-form support: a leading `/` on SYSTEM-USERNAME means
  // "regex". We pass plain names so reserved chars don't accidentally
  // toggle that mode. Defensive guard:
  if (osUser.startsWith('/') || /\s/.test(osUser)) {
    throw new Error(`renderPgIdent: osUser ${JSON.stringify(osUser)} contains reserved characters`);
  }
  const lines = [
    '# autopg pg_ident.conf — admin OS-user → autopg_admin map (Group 2).',
    '# Generated by autopg; manual edits are overwritten on upgrade.',
    '',
    '# MAPNAME       SYSTEM-USERNAME         PG-USERNAME',
    `${identMapName}          ${osUser}                ${adminRole}`,
    '',
  ];
  return lines.join('\n');
}

/**
 * Strip comments + blank lines, return the remaining content as an array
 * of trimmed non-empty lines. Used by `containsLegacyTrust` and the
 * idempotency check.
 */
function stripComments(content) {
  return content
    .split(/\r?\n/)
    .map((l) => l.replace(/#.*$/, '').trim())
    .filter(Boolean);
}

/**
 * Returns true if the given pg_hba.conf body has any `trust` method line
 * outside of comments. Used both for legacy detection AND for the post-
 * write CI smoke check (acceptance criterion: `grep -E '\btrust\b'` → 0).
 *
 * @param {string} content
 * @returns {boolean}
 */
export function containsLegacyTrust(content) {
  const tokenized = stripComments(content);
  return tokenized.some((line) => /\btrust\b/.test(line));
}

/**
 * Atomic write helper. write-tmp → rename so a crash mid-write never
 * leaves an empty pg_hba.conf (which would lock everyone out).
 */
function writeAtomic(filePath, body, mode) {
  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
  const tmp = `${filePath}.tmp.${process.pid}.${Date.now()}`;
  fs.writeFileSync(tmp, body, { mode });
  fs.renameSync(tmp, filePath);
  fs.chmodSync(filePath, mode);
}

/**
 * Migrate (or first-time install) the pg_hba.conf + pg_ident.conf files
 * inside `databaseDir` to the B1-fixed layout. Idempotent: if the on-disk
 * content already matches the rendered template byte-for-byte, returns
 * `idempotent-skip` without touching either file.
 *
 * Otherwise:
 *   - Writes pg_hba.conf with the canonical body (mode 0600).
 *   - Writes pg_ident.conf with the autopg map for the host OS user
 *     (mode 0600).
 *   - Calls opts.signalReload() if provided so the postmaster picks up
 *     the new config (the caller knows how to address the running
 *     postgres process — typically via SIGHUP).
 *   - Emits an audit event (`pg_hba_rewritten` / `pg_hba_idempotent_skip`).
 *
 * @param {string} databaseDir - PG data directory (the one initdb wrote into)
 * @param {object} [opts]
 * @param {string} [opts.osUser] - override host OS user (default: os.userInfo().username)
 * @param {string} [opts.adminRole]
 * @param {string} [opts.identMapName]
 * @param {() => (void|Promise<void>)} [opts.signalReload]
 * @param {object} [opts.logger] - pino-shaped logger
 * @returns {Promise<{status: 'rewritten'|'idempotent-skip', hbaPath: string, identPath: string, hadLegacyTrust: boolean}>}
 */
export async function migratePgHba(databaseDir, opts = {}) {
  if (!databaseDir || typeof databaseDir !== 'string') {
    throw new Error('migratePgHba: databaseDir is required');
  }
  const osUser = opts.osUser || os.userInfo().username;
  const adminRole = opts.adminRole || ADMIN_ROLE;
  const identMapName = opts.identMapName || IDENT_MAP_NAME;
  const logger = opts.logger;

  const hbaPath = path.join(databaseDir, HBA_FILENAME);
  const identPath = path.join(databaseDir, IDENT_FILENAME);

  const desiredHba = renderPgHba({ adminRole, identMapName });
  const desiredIdent = renderPgIdent({ osUser, adminRole, identMapName });

  let existingHba = null;
  if (fs.existsSync(hbaPath)) {
    existingHba = fs.readFileSync(hbaPath, 'utf8');
  }
  let existingIdent = null;
  if (fs.existsSync(identPath)) {
    existingIdent = fs.readFileSync(identPath, 'utf8');
  }

  const hadLegacyTrust = existingHba ? containsLegacyTrust(existingHba) : false;
  const hbaMatches = existingHba === desiredHba;
  const identMatches = existingIdent === desiredIdent;

  if (hbaMatches && identMatches) {
    audit(AUDIT_EVENTS.PG_HBA_IDEMPOTENT_SKIP, {
      hba_path: hbaPath,
      ident_path: identPath,
    });
    logger?.debug?.({ hbaPath, identPath }, 'pg-hba: idempotent-skip');
    return { status: 'idempotent-skip', hbaPath, identPath, hadLegacyTrust: false };
  }

  writeAtomic(hbaPath, desiredHba, 0o600);
  writeAtomic(identPath, desiredIdent, 0o600);

  // Defence-in-depth — the rendered template should never contain `trust`,
  // but assert before we ask postgres to reload it. A failed assert here
  // means the template was edited carelessly; bail before exposing a
  // half-written hba to a running postmaster.
  if (containsLegacyTrust(desiredHba)) {
    throw new Error('migratePgHba: rendered template contains a `trust` predicate (Sentinel B1 violation)');
  }

  if (typeof opts.signalReload === 'function') {
    try {
      await opts.signalReload();
    } catch (err) {
      logger?.warn?.({ err: err.message }, 'pg-hba: signalReload failed (config written, reload deferred)');
    }
  }

  audit(AUDIT_EVENTS.PG_HBA_REWRITTEN, {
    hba_path: hbaPath,
    ident_path: identPath,
    had_legacy_trust: hadLegacyTrust,
    os_user: osUser,
    admin_role: adminRole,
  });
  logger?.info?.(
    { hbaPath, identPath, hadLegacyTrust, osUser, adminRole },
    'pg-hba: B1-fixed layout written'
  );

  return { status: 'rewritten', hbaPath, identPath, hadLegacyTrust };
}

